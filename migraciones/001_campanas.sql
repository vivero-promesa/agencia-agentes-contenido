-- 1. Campañas: la idea que dura meses
create table if not exists public.campanas (
    id              bigint generated by default as identity primary key,
    codigo          text unique,                       -- ej. VH-001, viaja en los enlaces de WhatsApp
    nombre          text not null,
    idea_central    text not null,                     -- plataforma / gran idea
    mensaje_clave   text not null,                     -- lo que TODA pieza refuerza
    insight         text,                              -- verdad de la audiencia
    objetivo        text,                              -- resultado medible
    audiencia       text default 'institucional',      -- institucional | viverista
    tono_extra      text,
    fecha_inicio    date default current_date,
    fecha_fin       date,
    estado          text default 'borrador'
                    check (estado in ('borrador','activa','pausada','cerrada')),
    fecha_creacion  timestamptz default now()
);

-- 2. Calendario editorial: qué pieza, qué canal, qué pilar, qué día
create table if not exists public.calendario_contenidos (
    id              bigint generated by default as identity primary key,
    campana_id      bigint references public.campanas(id) on delete cascade,
    fecha           date not null,
    canal           text not null,                     -- BLOG | SEO | WHATSAPP | VIDEO | TEXTO
    pilar           text not null,                     -- oficio | abastecer | saber | lotes
    audiencia       text default 'institucional',
    tema            text not null,
    angulo          text,
    estado          text default 'pendiente'
                    check (estado in ('pendiente','generado','aprobado','publicado')),
    historial_id    text,                              -- pieza generada en historial_contenidos
    fecha_creacion  timestamptz default now()
);
create index if not exists calendario_campana_fecha_idx
    on public.calendario_contenidos (campana_id, fecha);

-- 3. Historial: cada pieza sabe a qué campaña, pilar y canal pertenece,
--    y dónde y cuándo se publicó
alter table public.historial_contenidos add column if not exists campana_id        bigint references public.campanas(id) on delete set null;
alter table public.historial_contenidos add column if not exists calendario_id     bigint references public.calendario_contenidos(id) on delete set null;
alter table public.historial_contenidos add column if not exists pilar             text;
alter table public.historial_contenidos add column if not exists canal             text;
alter table public.historial_contenidos add column if not exists audiencia         text;
alter table public.historial_contenidos add column if not exists fecha_publicacion date;
alter table public.historial_contenidos add column if not exists url_publicada     text;
create index if not exists historial_campana_idx
    on public.historial_contenidos (campana_id, fecha_creacion desc);

